//Arithmetics Oprators
let a = 10;
let b = 3;

console.log("a + b : ", a + b);
console.log("a - b : ", a - b);
console.log("a * b : ", a * b);
console.log("a / b : ", a / b);
console.log("a % b : ", a % b);
console.log("a ** b : ", a ** b);

let c = a++;
console.log(a);
console.log(c);

let d = ++a;
console.log(a);
console.log(d);

let e = b--;
console.log(b);
console.log(e);

let f = --b;
console.log(b);
console.log(f);
